"""Vault провайдеров: AES-256-GCM, версия формата, ключ и подмена.

Offline: временные каталоги, никаких сетевых вызовов.
"""

from __future__ import annotations

import base64
import json
import stat
from pathlib import Path

import pytest

from core.llm.provider_secrets import (
    ProviderSecretStore,
    ProviderSecretsError,
    _derive_legacy,
    _legacy_encrypt,
)

KEY = "test-master-key-for-provider-vault"


def _store(tmp_path: Path, **env: str) -> ProviderSecretStore:
    base = {"NEYRA_VAULT_KEY": KEY, **env}
    return ProviderSecretStore(tmp_path / "secrets", env=base)


def _file(store: ProviderSecretStore) -> dict:
    return json.loads(store.path.read_text(encoding="utf-8"))


def test_aesgcm_roundtrip_has_version_2_and_12_byte_nonce(tmp_path: Path):
    store = _store(tmp_path)
    store.set("openai", "sk-test-0123456789")
    assert store.get("openai") == "sk-test-0123456789"
    assert store.get_strict("openai") == "sk-test-0123456789"

    raw = _file(store)
    assert raw["version"] == 2
    item = raw["items"]["openai"]
    assert item["v"] == 2
    assert len(base64.b64decode(item["nonce"])) == 12
    assert "tag" not in item
    assert "sk-test-0123456789" not in store.path.read_text(encoding="utf-8")


def test_fixed_aesgcm_vector_is_stable(tmp_path: Path, monkeypatch):
    """Регрессионный вектор формата: смена схемы/полей не должна пройти незаметно."""
    monkeypatch.setattr("core.llm.provider_secrets.secrets.token_bytes", lambda n: bytes(range(n)))
    store = _store(tmp_path)
    store.set("openai", "sk-vector")
    item = _file(store)["items"]["openai"]
    assert item["nonce"] == base64.b64encode(bytes(range(12))).decode()
    assert item["ct"] == "eAM14yIJQs9rXhp0wKe4F9hjIYdtD+Qmlw=="
    assert store.get("openai") == "sk-vector"


def test_tampered_ciphertext_nonce_and_name_are_rejected(tmp_path: Path):
    store = _store(tmp_path)
    store.set("openai", "sk-secret-value")

    raw = _file(store)
    ct = bytearray(base64.b64decode(raw["items"]["openai"]["ct"]))
    ct[0] ^= 0xFF
    raw["items"]["openai"]["ct"] = base64.b64encode(bytes(ct)).decode()
    store.path.write_text(json.dumps(raw), encoding="utf-8")
    tampered = _store(tmp_path)
    assert tampered.get("openai") == ""
    with pytest.raises(ProviderSecretsError):
        tampered.get_strict("openai")

    store = _store(tmp_path)
    store.set("openai", "sk-secret-value")
    raw = _file(store)
    nonce = bytearray(base64.b64decode(raw["items"]["openai"]["nonce"]))
    nonce[0] ^= 0xFF
    raw["items"]["openai"]["nonce"] = base64.b64encode(bytes(nonce)).decode()
    store.path.write_text(json.dumps(raw), encoding="utf-8")
    with pytest.raises(ProviderSecretsError):
        _store(tmp_path).get_strict("openai")

    store = _store(tmp_path)
    store.set("openai", "sk-secret-value")
    raw = _file(store)
    raw["items"]["other"] = raw["items"]["openai"]
    store.path.write_text(json.dumps(raw), encoding="utf-8")
    assert _store(tmp_path).get("other") == ""
    with pytest.raises(ProviderSecretsError):
        _store(tmp_path).get_strict("other")


def test_legacy_v1_is_read_and_reencrypted_as_v2(tmp_path: Path):
    store = _store(tmp_path)
    # Собираем старую запись ровно так, как её писал v1.
    legacy_master = _derive_legacy(KEY)
    nonce = b"0123456789abcdef"
    ct, tag = _legacy_encrypt(legacy_master, nonce, b"legacy-key", b"legacy")
    store.dir.mkdir(parents=True, exist_ok=True)
    store.path.write_text(
        json.dumps(
            {
                "version": 1,
                "items": {
                    "legacy": {
                        "nonce": base64.b64encode(nonce).decode(),
                        "ct": base64.b64encode(ct).decode(),
                        "tag": base64.b64encode(tag).decode(),
                        "updated_at": "2026-01-01T00:00:00+00:00",
                    }
                },
            }
        ),
        encoding="utf-8",
    )
    assert store.get("legacy") == "legacy-key"
    store.set("legacy", "legacy-key")
    raw = _file(store)
    assert raw["version"] == 2
    assert raw["items"]["legacy"]["v"] == 2
    assert store.get("legacy") == "legacy-key"


def test_without_master_key_store_refuses_and_does_not_create_vault_key(tmp_path: Path):
    store = ProviderSecretStore(tmp_path / "secrets", env={})
    with pytest.raises(ProviderSecretsError, match="NEYRA_VAULT_KEY"):
        store.set("openai", "sk-secret")
    with pytest.raises(ProviderSecretsError, match="NEYRA_VAULT_KEY"):
        store.verify()
    assert not (tmp_path / "secrets" / "vault.key").exists()


def test_dev_flag_is_the_only_autogenerated_key_path(tmp_path: Path):
    store = ProviderSecretStore(tmp_path / "secrets", env={"NEYRA_VAULT_DEV": "1"})
    store.set("openai", "sk-dev-secret")
    key_path = tmp_path / "secrets" / "vault.key"
    assert key_path.is_file()
    assert stat.S_IMODE(key_path.stat().st_mode) == 0o600
    assert store.get("openai") == "sk-dev-secret"


def test_lost_key_makes_verify_and_strict_get_fail_loudly(tmp_path: Path):
    store = _store(tmp_path)
    store.set("openai", "sk-secret")
    wrong = ProviderSecretStore(tmp_path / "secrets", env={"NEYRA_VAULT_KEY": "another-key"})
    with pytest.raises(ProviderSecretsError, match="не может расшифровать"):
        wrong.verify()
    with pytest.raises(ProviderSecretsError, match="не расшифровывается"):
        wrong.get_strict("openai")


def test_verify_is_quiet_when_store_is_empty(tmp_path: Path):
    _store(tmp_path).verify()
